inline const char *Find(const char *input) {
    if (!input) return nullptr;
    size_t length=std::strlen(input);
    while (length && (input[length-1]=='\n' || input[length-1]=='\r')) --length;
    const char *key = *input == '#' ? input+1 : input;
    if (!std::strncmp(key,"Cstrike_TitlesTXT_",18)) key += 18;
    const size_t keyLength=length>=size_t(key-input)?length-size_t(key-input):0;
    size_t count=0; const Entry *entries=Entries(count);
    for (size_t i=0;i<count;++i) {
        const Entry &entry=entries[i];
        if (keyLength==std::strlen(entry.key) && !std::memcmp(key,entry.key,keyLength)) return entry.text;
        size_t englishLength=std::strlen(entry.english);
        while (englishLength && (entry.english[englishLength-1]=='\n' || entry.english[englishLength-1]=='\r')) --englishLength;
        if (englishLength && length==englishLength
            && !std::memcmp(input,entry.english,length)) return entry.text;
    }
    return nullptr;
}
